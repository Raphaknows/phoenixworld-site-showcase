export const vert = [
  'attribute vec3 aAsh; attribute vec3 aPhx; attribute vec3 aTxt; attribute vec3 aLat; attribute vec4 aRnd;',
  'uniform float uTime, uIntro, uMorph, uText, uPx, uScale, uFlap, uPush, uBurst, uHeat;',
  'uniform vec2 uOffset, uPointer, uBurstAt;',
  'varying vec3 vColor; varying float vAlpha;',
  'float ease(float t){ return t*t*(3.0-2.0*t); }',
  'mat3 rotY(float a){ float c=cos(a), s=sin(a); return mat3(c,0.0,-s, 0.0,1.0,0.0, s,0.0,c); }',
  'mat3 rotX(float a){ float c=cos(a), s=sin(a); return mat3(1.0,0.0,0.0, 0.0,c,s, 0.0,-s,c); }',
  'void main(){',
  '  float ph = aRnd.w * 6.2831;',
  '  float di = ease(clamp((uIntro - aRnd.x*0.5)/0.5, 0.0, 1.0));',
  '  vec3 phx = aPhx;',
  '  float wx = abs(phx.x);',
  '  float wing = smoothstep(0.6, 4.6, wx);',
  '  float beat = sin(uTime*1.5 - wx*0.25);',
  '  phx.y += beat*0.42*wing*wing*uFlap;',
  '  phx.z += (beat*0.7 - 0.2)*wing*uFlap;',
  '  phx.x *= 1.0 - 0.05*beat*wing*uFlap;',
  '  phx += vec3(sin(uTime*1.3+ph), cos(uTime*1.1+ph*1.3), sin(uTime*0.9+ph))*0.03;',
  '  float tail = smoothstep(-1.2, -3.7, phx.y);',
  '  phx.x += sin(uTime*3.0 + phx.y*2.0 + ph)*0.09*tail*uFlap;',
  '  float dt = ease(clamp((uText - aRnd.x*0.4)/0.6, 0.0, 1.0));',
  '  float ft = 4.0*dt*(1.0-dt);',
  '  vec3 txt = aTxt + vec3(sin(uTime*1.2+ph), cos(uTime+ph), 0.0)*0.015;',
  '  phx = mix(phx, txt, dt);',
  '  phx += vec3(sin(ph*2.0+uTime), cos(ph*3.0), sin(ph))*ft*0.9;',
  '  phx = phx*uScale + vec3(uOffset, 0.0);',
  '  vec3 a = aAsh; a.y += sin(uTime*0.7+ph)*0.15; a.x += cos(uTime*0.5+ph)*0.15;',
  '  vec3 p = mix(a, phx, di);',
  '  float fl = 4.0*di*(1.0-di);',
  '  p.x += sin(ph + uTime*2.0)*fl*0.9; p.z += cos(ph + uTime*2.0)*fl*0.9;',
  '  float dm = ease(clamp((uMorph - aRnd.x*0.4)/0.6, 0.0, 1.0));',
  '  float fm = 4.0*dm*(1.0-dm);',
  '  vec3 lat = rotX(0.42) * rotY(uTime*0.05 + 0.6) * aLat;',
  '  p = mix(p, lat, dm);',
  '  p += vec3(sin(ph*3.0), cos(ph*2.0), sin(ph*5.0))*fm*1.1;',
  // pointer wind and click burst, in world space on the z=0 plane
  '  vec2 dv = p.xy - uPointer; float dd = length(dv) + 1e-4;',
  '  float push = (1.0 - smoothstep(0.0, 1.7, dd)) * uPush;',
  '  p.xy += dv/dd * push * 0.85; p.z += push*0.7;',
  '  vec2 bv = p.xy - uBurstAt; float bd = length(bv) + 1e-4;',
  '  float ring = exp(-bd*0.45) * uBurst;',
  '  p.xy += bv/bd * ring * 2.4; p.z += ring*1.5*sin(ph);',
  '  vec4 mv = modelViewMatrix * vec4(p, 1.0);',
  '  gl_Position = projectionMatrix * mv;',
  '  gl_PointSize = aRnd.y * uPx * (26.0 / -mv.z) * (1.0 + fl*1.4 + fm*1.4 + ft*1.2 + ring*1.5) * (0.9 + uHeat*0.25);',
  '  float t = clamp((aPhx.y + 4.0)/8.4, 0.0, 1.0);',
  '  vec3 cRed = vec3(0.80,0.14,0.05), cEmb = vec3(1.0,0.42,0.10), cGold = vec3(1.0,0.76,0.38);',
  '  vec3 cp = mix(mix(cRed, cEmb, t/0.45), mix(cEmb, cGold, (t-0.45)/0.55), step(0.45, t));',
  '  cp = mix(cp, cGold, smoothstep(3.0, 5.0, wx)*0.6);',
  '  vec3 ct = mix(cEmb, cGold, clamp(aTxt.y*0.35 + 0.55, 0.0, 1.0));',
  '  cp = mix(cp, ct, dt);',
  '  cp = mix(cp, vec3(1.0,0.95,0.82), step(0.965, aRnd.z));',
  '  cp *= 0.8 + uHeat*0.45;',
  '  vec3 c = mix(vec3(0.32,0.28,0.26), cp, di);',
  '  float pulse = smoothstep(0.82, 1.0, sin(aLat.x*0.7 + aLat.z*0.4 - uTime*1.8)*0.5 + 0.5);',
  '  vec3 cl = mix(vec3(0.36,0.88,1.0), cEmb, step(0.86, aRnd.z));',
  '  cl *= 0.5 + pulse*1.0;',
  '  vColor = mix(c, cl, dm) + vec3(1.0,0.7,0.35)*(ring*0.9 + push*0.3);',
  '  vAlpha = mix(mix(0.3, 0.9, di), 0.7, dm);',
  '}'
].join('\n');
